"""Regenerate (or check) the runtime lock ``requirements.lock.txt`` and its digest (infrastructure roadmap D3).

  python scripts/regenerate_lock.py            # resolve requirements.txt in a fresh virtual environment (needs network),
                                               # rewrite requirements.lock.txt and requirements.lock.sha256
  python scripts/regenerate_lock.py --check    # offline: the lock is in canonical form, its digest matches, and it covers
                                               # every direct pin of requirements.txt at the same version

The lock lists every installed runtime distribution (direct and transitive) with an exact version. CI installs
from it (``pip install -r requirements.lock.txt -r requirements-dev.txt``) and then runs
``check_environment.py --strict-lock``, so a drifted environment fails instead of passing silently.

Regenerate on Linux with the CI interpreter (Python 3.11) when the pins change, in a PR that changes nothing else
(docs/dependency_management.md). Packages that only a different platform needs (for example ``colorama`` on
Windows) are then absent from the lock; pip still installs them as dependencies on that platform.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements.lock.txt"
DIGEST = ROOT / "requirements.lock.sha256"
DIRECT = ROOT / "requirements.txt"
HEADER = ("# Generated by scripts/regenerate_lock.py from requirements.txt; do not edit by hand.\n"
          "# Check with `python scripts/regenerate_lock.py --check`; CI installs from this file.\n")
# Installer tooling that lives in every virtual environment but is not a runtime dependency.
EXCLUDED = {"pip", "setuptools", "wheel"}
_PIN = re.compile(r"([A-Za-z0-9_.-]+)==([^ ;]+)(?:\s*;.*)?")


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_pins(text: str) -> List[Tuple[str, str]]:
    pins = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = _PIN.fullmatch(line)
        if not match:
            raise ValueError(f"not an exact pin: {line!r}")
        pins.append((match.group(1), match.group(2)))
    return pins


def render_lock(packages: Iterable[Tuple[str, str]]) -> str:
    """Canonical lock text: header, then one ``name==version`` per line sorted by normalized name."""
    chosen: Dict[str, Tuple[str, str]] = {}
    for name, version in packages:
        if canonical(name) in EXCLUDED:
            continue
        previous = chosen.setdefault(canonical(name), (name, version))
        if previous[1] != version:
            raise ValueError(f"{name} resolved to two versions: {previous[1]} and {version}")
    body = "".join(f"{name}=={version}\n" for _, (name, version) in sorted(chosen.items()))
    return HEADER + body


def digest_line(lock_text: str) -> str:
    return f"{hashlib.sha256(lock_text.encode('utf-8')).hexdigest()}  {LOCK.name}\n"


def check(lock: Path = LOCK, digest: Path = DIGEST, direct: Path = DIRECT) -> List[str]:
    """Problems with the committed lock, without touching the network."""
    errors = []
    raw = lock.read_bytes()
    text = raw.decode("utf-8")
    try:
        pins = parse_pins(text)
    except ValueError as exc:
        return [str(exc)]
    if text != render_lock(pins):
        errors.append(f"{lock.name} is not in canonical form (header, sort order); run scripts/regenerate_lock.py")
    expected = digest.read_text(encoding="ascii").split()
    if len(expected) != 2 or expected[1] != lock.name:
        errors.append(f"{digest.name} must read '<sha256>  {lock.name}'")
    elif expected[0] != hashlib.sha256(raw).hexdigest():
        errors.append(f"{digest.name} does not match {lock.name}")
    locked = {canonical(name): version for name, version in pins}
    if len(locked) != len(pins):
        errors.append(f"{lock.name} lists a distribution twice")
    for name, version in parse_pins(direct.read_text(encoding="utf-8")):
        if canonical(name) not in locked:
            errors.append(f"{name}=={version} from {direct.name} is missing from the lock")
        elif locked[canonical(name)] != version:
            errors.append(f"{name}: {direct.name} pins {version}, the lock has {locked[canonical(name)]}")
    return errors


def resolve(direct: Path = DIRECT, python: Optional[str] = None) -> List[Tuple[str, str]]:
    """Install the direct pins into a throwaway virtual environment and read back what pip resolved."""
    with tempfile.TemporaryDirectory(prefix="lock-resolve-") as tmp:
        env = Path(tmp) / "venv"
        subprocess.run([python or sys.executable, "-m", "venv", str(env)], check=True)
        exe = env / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
        subprocess.run([str(exe), "-m", "pip", "install", "--disable-pip-version-check", "-r", str(direct)], check=True)
        subprocess.run([str(exe), "-m", "pip", "check"], check=True)
        listing = subprocess.run([str(exe), "-m", "pip", "list", "--format=json", "--disable-pip-version-check"],
                                 check=True, capture_output=True, text=True).stdout
    return [(item["name"], item["version"]) for item in json.loads(listing)]


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="offline consistency check; changes nothing")
    parser.add_argument("--python", help="interpreter for the throwaway environment (default: this one)")
    args = parser.parse_args(argv)
    if args.check:
        errors = check()
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        if not errors:
            print(f"{LOCK.name}: canonical form, digest and direct pins verified ({len(parse_pins(LOCK.read_text(encoding='utf-8')))} packages)")
        return 1 if errors else 0
    text = render_lock(resolve(python=args.python))
    LOCK.write_bytes(text.encode("utf-8"))
    DIGEST.write_bytes(digest_line(text).encode("ascii"))
    print(f"wrote {LOCK.name} ({len(parse_pins(text))} packages) and {DIGEST.name}; review the diff before committing")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
